import crypto from 'node:crypto';

// The only inline script: flags JS support before first paint so the mobile
// menu and bag never flash in their no-JS state. Allowed by hash, not by
// 'unsafe-inline'.
export const INLINE_SCRIPT = "document.documentElement.classList.add('js')";

const sha256 = (s) => `'sha256-${crypto.createHash('sha256').update(s).digest('base64')}'`;

export function csp() {
  const directives = {
    'default-src': ["'none'"],
    'script-src': ["'self'", sha256(INLINE_SCRIPT)],
    'style-src': ["'self'"],
    'img-src': ["'self'", 'data:'],
    'font-src': ["'self'"],
    'connect-src': ["'self'"],
    'manifest-src': ["'self'"],
    'base-uri': ["'none'"],
    'form-action': ["'none'"],
    'object-src': ["'none'"],
    'frame-ancestors': ["'none'"],
    'upgrade-insecure-requests': [],
  };
  const render = (skip = []) => Object.entries(directives)
    .filter(([k]) => !skip.includes(k))
    .map(([k, v]) => [k, ...v].join(' ')).join('; ');
  // frame-ancestors is ignored (and warned about) inside <meta>.
  return { header: render(), meta: render(['frame-ancestors']), inline: INLINE_SCRIPT };
}

export const SECURITY_HEADERS = (policy) => ({
  'Content-Security-Policy': policy,
  'Strict-Transport-Security': 'max-age=31536000',
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'accelerometer=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=(), browsing-topics=()',
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Resource-Policy': 'same-origin',
  'X-Permitted-Cross-Domain-Policies': 'none',
});

// Apache / LiteSpeed config for Hostinger shared hosting.
export function htaccess({ policy, redirects, base }) {
  const headers = Object.entries(SECURITY_HEADERS(policy))
    .map(([k, v]) => `  Header always set ${k} "${v}"`).join('\n');
  return `# Generated by build/security.mjs. Edit that file, not this one.

Options -Indexes -MultiViews
ServerSignature Off
AddDefaultCharset utf-8
DirectoryIndex index.html
ErrorDocument 404 ${base}404.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # HTTPS and the bare domain only.
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !https
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
  RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]
  RewriteRule ^ https://%1%{REQUEST_URI} [L,R=301]

  # Old URLs from the first version of the site.
${redirects.map(([from, to]) => `  RewriteRule ^${from.replace(/\./g, '\\.').replace(/\/$/, '/?')}$ ${to} [L,R=301]`).join('\n')}

  # Only GET and HEAD: this is a static site.
  RewriteCond %{REQUEST_METHOD} !^(GET|HEAD)$
  RewriteRule ^ - [F]

  # Never serve dotfiles (except .well-known), source maps or backups.
  RewriteRule (^|/)\\.(?!well-known/) - [F]
  RewriteRule \\.(map|bak|old|orig|swp|log|sh|sql|env|ini|lock|json\\.gz)$ - [F,NC]
</IfModule>

<IfModule mod_headers.c>
${headers}
  Header unset X-Powered-By
  Header always unset X-Powered-By

  # Hashed assets never change; pages always revalidate.
  <FilesMatch "\\.[0-9a-f]{10}\\.(css|js|woff2|avif|webp|jpg|png)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(html|xml|txt|webmanifest)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>

<IfModule mod_mime.c>
  AddType application/manifest+json .webmanifest
  AddType image/avif .avif
  AddType font/woff2 .woff2
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json application/manifest+json image/svg+xml
</IfModule>
`;
}

export function securityTxt({ site, expires }) {
  return `Contact: https://wa.me/${site.whatsapp[0].number}
Expires: ${expires}
Preferred-Languages: en, th, hi
Canonical: ${site.url}/.well-known/security.txt
`;
}
